/* Figures animées (bonshommes schématiques, 2 frames alternées comme un GIF).
   Chaque figure = 2 poses en SVG, alternées par une animation CSS (steps). */

function poseSVG(poses, opts) {
  opts = opts || {};
  const draw = (p, cls) => {
    let s = "";
    if (p.ground !== false) s += '<line x1="8" y1="122" x2="112" y2="122" class="gnd"/>';
    (p.rects || []).forEach(r => { s += '<rect x="' + r[0] + '" y="' + r[1] + '" width="' + (r[2]-r[0]) + '" height="' + (r[3]-r[1]) + '" class="box"/>'; });
    if (p.ellipse) s += '<ellipse cx="' + p.ellipse[0] + '" cy="' + p.ellipse[1] + '" rx="' + p.ellipse[2] + '" ry="' + p.ellipse[3] + '" class="dashline"/>';
    (p.lines || []).forEach(l => {
      s += '<polyline points="' + l.map(pt => pt.join(",")).join(" ") + '" class="limb' + (l.dashed ? " dashed" : "") + '"/>';
    });
    (p.dash || []).forEach(l => {
      s += '<polyline points="' + l.map(pt => pt.join(",")).join(" ") + '" class="dashline"/>';
    });
    if (p.head) s += '<circle cx="' + p.head[0] + '" cy="' + p.head[1] + '" r="8" class="head"/>';
    return '<g class="' + cls + '">' + s + "</g>";
  };
  const bbox = opts.viewBox || "0 0 120 130";
  return '<svg class="exfig" viewBox="' + bbox + '" aria-hidden="true">' + draw(poses[0], "poseA") + draw(poses[1], "poseB") + "</svg>";
}

